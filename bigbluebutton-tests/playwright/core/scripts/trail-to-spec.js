#!/usr/bin/env node
// Turns a repro trail copied from the client (debug window "Copy repro trail", or
// bbbTelemetry.trail() in the console) into a Playwright spec skeleton.
//
//   node core/scripts/trail-to-spec.js trail.json > repro/repro.spec.ts
//
// The trail records which control was used, never what was typed, so the skeleton
// marks where text must be filled in, and the assertion is always left to a human.

const fs = require('fs');
const path = require('path');

const ELEMENTS_FILE = path.join(__dirname, '..', 'elements.ts');
// Gaps worth calling out to whoever turns the skeleton into a test
const NOTABLE_GAP_MS = 2000;
// Clicks on these controls are the act of capturing the trail itself
const CAPTURE_CONTROLS = /^debugWindow/;

// data-test value -> elements.ts key, from entries such as  chatButton: 'button[data-test="chatButton"]'
function dataTestIndex() {
  const index = new Map();
  const source = fs.readFileSync(ELEMENTS_FILE, 'utf8');
  const entry = /^\s+(\w+):\s*['`]([^'`]*)\[data-test="([^"]+)"\]([^'`]*)['`],/gm;
  let match = entry.exec(source);
  while (match) {
    const [, key, before, dataTest, after] = match;
    // Prefer the plainest selector: no descendant parts, no nth
    const plain = !before.includes(' ') && !after.trim();
    if (!index.has(dataTest) || (plain && !index.get(dataTest).plain)) index.set(dataTest, { key, plain });
    match = entry.exec(source);
  }
  return index;
}

function clickStep(action, index) {
  if (!action.dataTest) {
    return [`// TODO: click on a <${action.tag || 'element'}> without data-test; add one in the client`];
  }
  if (action.ownDataTest === false) {
    // The data-test belongs to a container; aim at the control inside it
    return [
      `// TODO: the <${action.tag}> has no data-test of its own; add one in the client`,
      `await modPage.page.locator('[data-test="${action.dataTest}"] ${action.tag}').first().click();`,
    ];
  }
  const known = index.get(action.dataTest);
  if (known) return [`await modPage.waitAndClick(e.${known.key});`];
  return [
    `// TODO: add an elements.ts entry for data-test="${action.dataTest}"`,
    `await modPage.waitAndClick('[data-test="${action.dataTest}"]');`,
  ];
}

function steps(trail, index) {
  const lines = [];
  for (const action of trail.actions) {
    if (action.deltaMs >= NOTABLE_GAP_MS) lines.push(`// +${action.deltaMs} ms of inactivity in the original session`);
    if (action.type === 'click') {
      if (!CAPTURE_CONTROLS.test(action.dataTest)) lines.push(...clickStep(action, index));
    } else if (action.type === 'keydown') {
      const where = action.dataTest ? ` on ${action.dataTest}` : '';
      // Enter in a text field usually submits what was typed before it
      if (action.key === 'Enter' && (action.tag === 'textarea' || action.tag === 'input')) {
        lines.push(`// TODO: type what the user typed${where} (never recorded)`);
      }
      lines.push(`await modPage.page.keyboard.press('${action.key}');`);
    } else if (action.type === 'mutation') {
      const times = action.count ? ` x${action.count}` : '';
      lines.push(`// mutation ${action.operationName}${times}`);
    }
  }
  return lines;
}

function render(trail, index) {
  const { context } = trail;
  const lines = steps(trail, index);
  const body = lines.map((line) => `    ${line}`).join('\n');
  const usesElements = lines.some((line) => line.includes('(e.'));
  const elementsImport = usesElements ? "import { elements as e } from '../core/elements';\n" : '';
  return `// Generated by core/scripts/trail-to-spec.js from a repro trail captured at ${trail.capturedAt}
// Client ${context.clientBuild}, viewport ${context.viewport}, ${context.language}
// ${context.userAgent}
// Review every step, fill in the TODOs, then write the assertion that shows the bug.
${elementsImport}import { test } from '../core/setup/fixtures';
import { MultiUsers } from '../user/multiusers';

test.describe('Repro', () => {
  test('replays the captured actions', async ({ browser, context, page }, testInfo) => {
    const users = new MultiUsers(browser, context);
    await users.initModPage(page, { testInfo });
    const { modPage } = users;

${body}

    // TODO: assert the behavior that was wrong
  });
});
`;
}

function main() {
  const [file] = process.argv.slice(2);
  if (!file) {
    console.error('usage: node core/scripts/trail-to-spec.js <trail.json>');
    process.exit(1);
  }
  const trail = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (trail.version !== 1 || !Array.isArray(trail.actions)) {
    console.error('not a repro trail (expected version 1 with an actions array)');
    process.exit(1);
  }
  process.stdout.write(render(trail, dataTestIndex()));
}

main();
