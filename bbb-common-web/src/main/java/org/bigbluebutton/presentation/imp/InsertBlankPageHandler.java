package org.bigbluebutton.presentation.imp;

import java.io.File;
import java.io.IOException;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;

import org.apache.commons.io.FileUtils;
import org.bigbluebutton.api.Util;
import org.bigbluebutton.api.messaging.messages.InsertBlankPage;
import org.bigbluebutton.api2.IBbbWebApiGWApp;
import org.bigbluebutton.api2.MsgBuilder;
import org.bigbluebutton.common2.msgs.BbbCommonEnvCoreMsg;
import org.bigbluebutton.presentation.DocumentConversionService;
import org.bigbluebutton.presentation.SupportedFileTypes;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Makes the blank page of an insert: writes a one-page PDF the size bbb-apps-akka asked for, and starts it
 * as the file of the insert, so it is converted and delivered like an uploaded file. Works on an executor of
 * its own, never on the thread of MeetingService, which serves every meeting.
 */
public class InsertBlankPageHandler {
    private static final Logger log = LoggerFactory.getLogger(InsertBlankPageHandler.class);

    // Sized as the pool of PresentationUrlDownloadService; the work starts right away.
    private final ScheduledExecutorService executor = Executors.newScheduledThreadPool(3);

    private DocumentConversionService documentConversionService;
    private IBbbWebApiGWApp gw;
    private InsertPagesDeliveryService insertPagesDeliveryService;
    private String presentationDir;
    private String presentationBaseURL;

    public void handle(InsertBlankPage msg) {
        executor.execute(() -> makeBlankPage(msg));
    }

    void makeBlankPage(InsertBlankPage msg) {
        File uploadDir = null;
        boolean registered = false;
        try {
            uploadDir = Util.createPresentationDir(msg.meetingId, presentationDir, msg.uploadPresentationId);
            if (uploadDir == null) {
                throw new IOException("Could not create the directory of upload " + msg.uploadPresentationId);
            }
            File file = new File(uploadDir, Util.createNewFilename(msg.uploadPresentationId, "pdf"));
            BlankPagePdf.write(msg.width, msg.height, file);

            InsertPagesDeliveryService.Start start = insertPagesDeliveryService.startFromFile(msg.podId, msg.meetingId,
                    msg.uploadPresentationId, msg.filename, file, presentationBaseURL, "", msg.intent, msg.userId);
            registered = true;
            if (!start.accepted) {
                // Mapped to the failure of the insert by the delivery service.
                documentConversionService.sendDocConversionFailedOnMimeType(start.pres, SupportedFileTypes.detectMimeType(file), "pdf");
                return;
            }

            log.info("Converting a blank page of {}x{} for upload [{}] in meeting [{}]", msg.width, msg.height,
                    msg.uploadPresentationId, msg.meetingId);
            gw.sendInsertPagesMessages(Collections.singletonList(start.progress));
            // Generated by the server: no virus scan. It counts against the meeting's conversion limit.
            documentConversionService.processDocument(start.pres, false);
        } catch (Throwable e) {
            log.error("Failed to make the blank page of upload [{}] in meeting [{}]", msg.uploadPresentationId, msg.meetingId, e);
            if (registered) {
                List<BbbCommonEnvCoreMsg> failure = insertPagesDeliveryService.failureFor(msg.uploadPresentationId, e.toString());
                if (failure != null) gw.sendInsertPagesMessages(failure);
            } else {
                gw.sendInsertPagesMessages(Collections.singletonList(MsgBuilder.buildPresentationInsertPagesFailedSysMsg(
                        msg.meetingId, msg.userId, msg.podId, msg.uploadPresentationId,
                        InsertPagesDeliveryService.ERROR_FAILED, e.toString())));
                if (uploadDir != null) FileUtils.deleteQuietly(uploadDir);
            }
        }
    }

    public void stop() {
        executor.shutdownNow();
    }

    public void setDocumentConversionService(DocumentConversionService documentConversionService) {
        this.documentConversionService = documentConversionService;
    }

    public void setGw(IBbbWebApiGWApp gw) {
        this.gw = gw;
    }

    public void setInsertPagesDeliveryService(InsertPagesDeliveryService insertPagesDeliveryService) {
        this.insertPagesDeliveryService = insertPagesDeliveryService;
    }

    public void setPresentationDir(String presentationDir) {
        this.presentationDir = presentationDir;
    }

    public void setPresentationBaseURL(String presentationBaseURL) {
        this.presentationBaseURL = presentationBaseURL;
    }
}
