#!/usr/bin/env bash
# Interface tests for the expectations check in docker/tests/golden/run-golden.sh.
# Protected: written before the implementation; the runner must pass them unchanged.
#
# Contract (extends the one in test-golden.sh):
#   If a case directory contains `expectations.yaml`, run-golden.sh also evaluates it (no extra
#   option needed) and prints, per case, `EXPECT-PASS <name>` or one line per failed check:
#     EXPECT-FAIL <name>: <file>: <selector>: <reason>
#     EXPECT-FAIL <name>: must_fail: <case description>: <reason>
#     EXPECT-FAIL <name>: uid: <reason>
#   A case with any EXPECT-FAIL makes the run exit 1. An invalid expectations.yaml (unknown key or
#   operator, missing `file`) exits 2 with a message naming the problem.
#
#   expectations.yaml:
#     render:            # checks on the tree rendered with fixture.env
#       - file: <relpath below the render-only root>
#         format: yaml | json | properties | lines
#         checks:        # one operator per check
#           yaml/json:   {path: <yq path>, equals: <scalar>}   {path: <yq path>, absent: true}
#           properties:  {key: <key>, equals: <string>}        {key: <key>, absent: true}
#                        (`key = value` and `key=value` both parse; first occurrence wins)
#           lines:       {contains_line: <ERE>}                {no_line: <ERE>}
#           any format:  {matches: <ERE>, path|key: …}   value must match the ERE
#     must_fail:         # each runs the image with fixture.env modified; the entrypoint must exit
#       - {unset: VAR, message: <substring>}                 # non-zero and print <substring>
#       - {set: {VAR: value, …}, message: <substring>}       # values may contain newlines
#                        # and must not appear verbatim in the output
#     uid: {user: "UID:GID"}   # the render also succeeds under this user
#   Selectors in EXPECT-FAIL lines: the yq path, the properties key, or the ERE.
#
# Usage: docker/tests/golden/test-expectations.sh   (needs podman or docker; builds the selftest image)

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER="${RUN_GOLDEN:-$HERE/run-golden.sh}"
ENGINE="${CONTAINER_ENGINE:-$(command -v docker >/dev/null 2>&1 && echo docker || echo podman)}"
IMAGE=localhost/bbb-golden-selftest:test
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
SECRET=fixturebbbsharedsecretnotreal0000000000000000000

PASSED=0
FAILED=0
pass() { PASSED=$((PASSED + 1)); echo "ok   $1"; }
fail() { FAILED=$((FAILED + 1)); echo "FAIL $1${2:+: $2}"; }

[ -x "$RUNNER" ] || { echo "runner not found or not executable: $RUNNER"; exit 1; }
"$ENGINE" build -q -t "$IMAGE" -f "$HERE/selftest-image/Dockerfile" "$HERE/../.." >/dev/null

ROOT="$WORK/golden"
mkdir -p "$ROOT"
# A case whose expected/ tree is generated by --update first, so only expectations are under test.
newcase() { # name expectations-yaml
    local d="$ROOT/$1"
    mkdir -p "$d"
    printf '%s\n' "$IMAGE" >"$d/image"
    printf '%s\n' BBB_DOMAIN=bbb.example.com "BBB_SHARED_SECRET=$SECRET" SELFTEST_FORMATS=1 >"$d/fixture.env"
    printf '%s\n' "$2" >"$d/expectations.yaml"
    "$RUNNER" --engine "$ENGINE" --root "$ROOT" --update "$1" >/dev/null 2>&1 || true
}
run() {
    set +e
    "$RUNNER" --engine "$ENGINE" --root "$ROOT" "$@" >"$WORK/out" 2>&1
    RC=$?
    set -e
    OUT="$(cat "$WORK/out")"
}
expect_rc() { if [ "$RC" -eq "$2" ]; then pass "$1"; else fail "$1" "exit $RC, expected $2; output: $OUT"; fi; }
expect_line() { if grep -qE "$2" "$WORK/out"; then pass "$1"; else fail "$1" "no line /$2/ in: $OUT"; fi; }

GOOD='render:
  - file: etc/selftest/app.yaml
    format: yaml
    checks:
      - {path: .server.domain, equals: bbb.example.com}
      - {path: .server.workers, equals: 4}
      - {path: .server.tls, equals: true}
      - {path: .server.port, absent: true}
  - file: etc/selftest/app.properties
    format: properties
    checks:
      - {key: serverURL, equals: "https://bbb.example.com"}
      - {key: maxWorkers, equals: "4"}
      - {key: securitySalt, matches: "^fixture[a-z0-9]+$"}
      - {key: redisHost, absent: true}
  - file: etc/selftest/app.conf
    format: lines
    checks:
      - {contains_line: "^server_name bbb\\.example\\.com;$"}
      - {no_line: "^listen "}
must_fail:
  - {unset: BBB_DOMAIN, message: BBB_DOMAIN}
  - {set: {BBB_DOMAIN: "bbb.example.com\nevil"}, message: BBB_DOMAIN}
uid: {user: "12345:12345"}'

# --- all expectations hold ----------------------------------------------------------------------
newcase good "$GOOD"
run good
expect_rc "all expectations hold: exit 0" 0
expect_line "all expectations hold: EXPECT-PASS" "^EXPECT-PASS good$"
expect_line "golden check still runs: PASS" "^PASS good$"
if grep -q 'evil' "$WORK/out"; then fail "must_fail: set value not echoed"; else pass "must_fail: set value not echoed"; fi

# --- render checks fail ---------------------------------------------------------------------------
newcase badyaml "${GOOD/equals: bbb.example.com\}/equals: other.example.com\}}"
run badyaml
expect_rc "yaml equals violated: exit 1" 1
expect_line "yaml equals violated: reported" "^EXPECT-FAIL badyaml: etc/selftest/app.yaml: \.server\.domain: "

newcase badabsent "${GOOD/\{path: .server.port, absent: true\}/\{path: .server.tls, absent: true\}}"
run badabsent
expect_line "yaml absent violated: reported" "^EXPECT-FAIL badabsent: etc/selftest/app.yaml: \.server\.tls: "

newcase badprop "${GOOD/equals: \"4\"/equals: \"5\"}"
run badprop
expect_line "properties equals violated (spaced key = value): reported" "^EXPECT-FAIL badprop: etc/selftest/app.properties: maxWorkers: "

newcase badmatch "${GOOD/\^fixture\[a-z0-9\]+\$/^real}"
run badmatch
expect_line "properties matches violated: reported" "^EXPECT-FAIL badmatch: etc/selftest/app.properties: securitySalt: "

newcase badline "${GOOD/no_line: \"^listen \"/no_line: \"^workers=\"}"
run badline
expect_line "lines no_line violated: reported" "^EXPECT-FAIL badline: etc/selftest/app.conf: \^workers=: "

newcase missingfile "${GOOD/file: etc\/selftest\/app.conf/file: etc/selftest/nope.conf}"
run missingfile
expect_line "file not rendered: reported" "^EXPECT-FAIL missingfile: etc/selftest/nope.conf: "

# --- must_fail ------------------------------------------------------------------------------------
newcase notfail "${GOOD/unset: BBB_DOMAIN, message: BBB_DOMAIN/unset: SELFTEST_WORKERS, message: SELFTEST_WORKERS}"
run notfail
expect_line "must_fail case that succeeds: reported" "^EXPECT-FAIL notfail: must_fail: .*SELFTEST_WORKERS.*: "

newcase wrongmsg "${GOOD/unset: BBB_DOMAIN, message: BBB_DOMAIN/unset: BBB_DOMAIN, message: SOMETHING_ELSE}"
run wrongmsg
expect_line "must_fail message not printed: reported" "^EXPECT-FAIL wrongmsg: must_fail: .*BBB_DOMAIN.*: "

# --- invalid file, no file -------------------------------------------------------------------------
newcase invalid "${GOOD/equals: true\}/frobnicates: true\}}"
run invalid
expect_rc "unknown operator: exit 2" 2

mkdir -p "$ROOT/plain"
printf '%s\n' "$IMAGE" >"$ROOT/plain/image"
printf '%s\n' BBB_DOMAIN=bbb.example.com >"$ROOT/plain/fixture.env"
"$RUNNER" --engine "$ENGINE" --root "$ROOT" --update plain >/dev/null 2>&1 || true
run plain
expect_rc "case without expectations.yaml: exit 0" 0
if grep -q '^EXPECT' "$WORK/out"; then fail "no expectations file: no EXPECT lines"; else pass "no expectations file: no EXPECT lines"; fi

echo
echo "$PASSED passed, $FAILED failed"
[ "$FAILED" -eq 0 ]
